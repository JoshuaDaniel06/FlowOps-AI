def validate_sql_query(sql_text: str) -> Tuple[bool, str, str]:
    """
    Validates that the SQL statement is strictly read-only SELECT against approved tables.
    Returns (is_valid, sanitized_sql, error_reason).
    """
    cleaned = sql_text.strip()
    if not cleaned:
        return False, "", "Empty SQL query."

    # Remove markdown code block if present
    cleaned = re.sub(r"^```(?:sql)?\s*", "", cleaned, flags=re.IGNORECASE)
    cleaned = re.sub(r"\s*```$", "", cleaned)
    cleaned = cleaned.strip()

    # Reject comments that might disguise injections
    if "--" in cleaned or "/*" in cleaned or "*/" in cleaned:
        return False, "", "SQL comments (-- or /* */) are prohibited for security."

    # Parse with sqlparse
    parsed = sqlparse.parse(cleaned)
    if not parsed:
        return False, "", "Failed to parse SQL statement."

    if len(parsed) > 1:
        return False, "", "Multiple SQL statements are strictly prohibited."

    stmt = parsed[0]
    stmt_type = stmt.get_type()
    if stmt_type != "SELECT":
        return False, "", f"Prohibited statement type '{stmt_type}'. Only SELECT queries are permitted."

    # Check tokens recursively for forbidden keywords
    upper_query = cleaned.upper()
    for kw in FORBIDDEN_KEYWORDS:
        # Match as whole word
        pattern = r"\b" + re.escape(kw) + r"\b"
        if re.search(pattern, upper_query):
            return False, "", f"Prohibited keyword or function '{kw}' detected."

    # Verify tables referenced are in approved whitelist
    # Extract identifiers following FROM or JOIN
    from_join_pattern = re.compile(r"\b(?:FROM|JOIN)\s+([a-zA-Z0-9_\.\"]+)", re.IGNORECASE)
    matches = from_join_pattern.findall(cleaned)
    for tbl in matches:
        clean_tbl = tbl.replace('"', '').strip().lower()
        if clean_tbl not in APPROVED_TABLES:
            return False, "", f"Access to table '{clean_tbl}' is not permitted. Allowed tables: {', '.join(APPROVED_TABLES.keys())}."

    # Enforce LIMIT 50
    # Strip any trailing semicolon
    if cleaned.endswith(";"):
        cleaned = cleaned[:-1].strip()

    limit_match = re.search(r"\bLIMIT\s+(\d+)", cleaned, re.IGNORECASE)
    if limit_match:
        limit_val = int(limit_match.group(1))
        if limit_val > 50:
            cleaned = re.sub(r"\bLIMIT\s+\d+", "LIMIT 50", cleaned, flags=re.IGNORECASE)
    else:
        cleaned = f"{cleaned} LIMIT 50"

    return True, cleaned, ""


def execute_safe_sql(sql_query: str) -> Dict[str, Any]:
    """
    Executes a validated read-only SQL query with a 5-second timeout and 50-row limit.
    """
    start_time = time.time()
    try:
        with engine.connect() as conn:
            # Set session read-only and statement timeout
            conn.execute(text("SET TRANSACTION READ ONLY;"))
            conn.execute(text("SET LOCAL statement_timeout = 5000;"))

            result = conn.execute(text(sql_query))
            columns = list(result.keys())
            raw_rows = result.fetchall()

            formatted_rows = []
            for r in raw_rows:
                row_dict = {}
                for idx, col in enumerate(columns):
                    val = r[idx]
                    if hasattr(val, "isoformat"):
                        val = val.isoformat()
                    elif hasattr(val, "__float__") and not isinstance(val, (int, float)):
                        val = float(val)
                    row_dict[col] = val
                formatted_rows.append(row_dict)

            exec_duration_ms = round((time.time() - start_time) * 1000, 2)
            return {
                "success": True,
                "columns": columns,
                "rows": formatted_rows,
                "row_count": len(formatted_rows),
                "execution_duration_ms": exec_duration_ms,
                "sql": sql_query
            }
    except Exception as exc:
        exec_duration_ms = round((time.time() - start_time) * 1000, 2)
        return {
            "success": False,
            "error": str(exc),
            "execution_duration_ms": exec_duration_ms,
            "sql": sql_query
        }


def process_natural_language_sql(user_prompt: str) -> Dict[str, Any]:
    """
    End-to-end workflow:
    1. Generates read-only SQL from user prompt using Claude
    2. Validates SQL strictly
    3. Executes query safely in PostgreSQL
    4. Explains results in natural language
    """
    api_key = os.getenv("ANTHROPIC_API_KEY")
    model = os.getenv("CLAUDE_MODEL", "claude-sonnet-4-6")

    if not api_key:
        raise RuntimeError("ANTHROPIC_API_KEY is missing from environment.")

    client = Anthropic(api_key=api_key)

    # 1. Ask Claude to generate the query
    generation_prompt = f"""You are a specialized PostgreSQL query generator for FlowOps AI.
Given the following database schema, generate a single, read-only SELECT query that directly answers the user's question.

{SCHEMA_PROMPT_DOC}

RULES:
- Return ONLY the raw SQL query. Do not wrap in markdown or backticks.
- Strictly SELECT queries only. No INSERT, UPDATE, DELETE, DROP, or schema mutations.
- Always use standard PostgreSQL syntax.
- Order by relevant timestamp or ID descending when answering 'latest', 'recent', or 'last' questions.
- Use explicit column names instead of SELECT * when possible.
- Include a reasonable LIMIT clause (max 50).

User Question: {user_prompt}
"""

    resp = client.messages.create(
        model=model,
        max_tokens=400,
        messages=[{"role": "user", "content": generation_prompt}]
    )

    generated_sql = "".join(b.text for b in resp.content if b.type == "text").strip()
    gen_in_tokens = resp.usage.input_tokens
    gen_out_tokens = resp.usage.output_tokens

    # 2. Validate SQL
    is_valid, validated_sql, val_error = validate_sql_query(generated_sql)
    if not is_valid:
        return {
            "success": False,
            "sql": generated_sql,
            "error": f"SQL Safety Validation Failed: {val_error}",
            "answer": f"I could not execute the generated SQL because it violated security rules: {val_error}. Please rephrase your question to target standard operational records.",
            "columns": [],
            "rows": [],
            "row_count": 0,
            "model": model,
            "input_tokens": gen_in_tokens,
            "output_tokens": gen_out_tokens,
            "total_tokens": gen_in_tokens + gen_out_tokens,
            "estimated_cost_usd": round(((gen_in_tokens / 1e6) * 3.0) + ((gen_out_tokens / 1e6) * 15.0), 8)
        }

    # 3. Execute query
    exec_result = execute_safe_sql(validated_sql)
    if not exec_result["success"]:
        return {
            "success": False,
            "sql": validated_sql,
            "error": f"Database execution error: {exec_result['error']}",
            "answer": f"The query was validated but failed during database execution: {exec_result['error']}",
            "columns": [],
            "rows": [],
            "row_count": 0,
            "model": model,
            "input_tokens": gen_in_tokens,
            "output_tokens": gen_out_tokens,
            "total_tokens": gen_in_tokens + gen_out_tokens,
            "estimated_cost_usd": round(((gen_in_tokens / 1e6) * 3.0) + ((gen_out_tokens / 1e6) * 15.0), 8)
        }

    # 4. Generate natural-language explanation
    explanation_prompt = f"""You are FlowOps Bot. Explain the following SQL query results to the user in a concise, friendly, data-engineering oriented response.

User Question: {user_prompt}
Executed SQL:
{validated_sql}

Query Results ({exec_result['row_count']} rows returned):
{exec_result['rows'][:15]}

INSTRUCTIONS:
- Directly answer the user's question based on the returned rows.
- If 0 rows were returned, state clearly that no matching records were found in the database.
- Highlight key metrics, run IDs, row counts, durations, or anomalies if present.
- Keep the summary professional and concise.
"""

    resp_exp = client.messages.create(
        model=model,
        max_tokens=600,
        messages=[{"role": "user", "content": explanation_prompt}]
    )

    exp_text = "".join(b.text for b in resp_exp.content if b.type == "text").strip()
    total_in = gen_in_tokens + resp_exp.usage.input_tokens
    total_out = gen_out_tokens + resp_exp.usage.output_tokens
    total_tokens = total_in + total_out
    cost = round(((total_in / 1e6) * 3.0) + ((total_out / 1e6) * 15.0), 8)

    return {
        "success": True,
        "sql": validated_sql,
        "columns": exec_result["columns"],
        "rows": exec_result["rows"],
        "row_count": exec_result["row_count"],
        "execution_duration_ms": exec_result["execution_duration_ms"],
        "answer": exp_text,
        "model": model,
        "input_tokens": total_in,
        "output_tokens": total_out,
        "total_tokens": total_tokens,
        "estimated_cost_usd": cost
    }
